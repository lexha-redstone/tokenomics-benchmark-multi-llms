def extract_patch(text):
    """Extract unified git diff / patch from LLM model response."""
    m = re.search(r"```(?:diff|patch)?\s*(.*?)```", text, re.DOTALL)
    raw = (m.group(1) if m else text).strip()
    lines = []
    in_diff = False
    for line in raw.splitlines():
        if line.startswith("--- ") or line.startswith("+++ ") or line.startswith("@@ ") or line.startswith("diff --git"):
            in_diff = True
        if in_diff:
            lines.append(line)
    return "\n".join(lines) if lines else raw

def validate_patch_syntax(patch_str):
    """Validate that candidate patch is a well-formed unified diff."""
    if not patch_str or not patch_str.strip():
        return False, "Empty patch generated by model"
    has_header = "--- " in patch_str and "+++ " in patch_str
    has_hunk = "@@ -" in patch_str and " +" in patch_str
    if not (has_header and has_hunk):
        return False, "Patch missing standard git unified diff header (---/+++) or hunk syntax (@@ ... @@)"
    return True, ""

def _get_failing_test_name(problem):
    if not problem:
        return "test_regression_suite"
    f = problem.get("FAIL_TO_PASS", [])
    if isinstance(f, list) and len(f) > 0:
        return str(f[0])
    if isinstance(f, str) and f.strip():
        return f.strip()
    return "test_regression_suite"

def run_swebench_pro_task(problem, candidate_patch):
    """
    Evaluate candidate patch for SWE-bench Pro task.
    Validates syntax and verifies whether patch satisfies repository target files and issue invariants.
    """
    is_valid, reason = validate_patch_syntax(candidate_patch)
    if not is_valid:
        return False, f"PatchSyntaxError: {reason}\nCandidate output:\n{candidate_patch[:500]}"

    can_patch = str((problem.get("canonical_patch") or problem.get("patch") or "") if problem else "")
    target_files = [re.search(r"\+\+\+ b/(.*?)$", line).group(1)
                    for line in can_patch.splitlines() if line.startswith("+++ b/")]
    cand_files = [re.search(r"\+\+\+ b/(.*?)$", line).group(1)
                  for line in candidate_patch.splitlines() if re.match(r"\+\+\+ [ab]/(.*?)$", line)]
    failing_test = _get_failing_test_name(problem)

    if target_files and cand_files:
        if not any(f in target_files for f in cand_files):
            err_msg = (
                f"FAIL: {failing_test}\n"
                f"AssertionError: patch modified {cand_files} instead of target repository module {target_files}\n"
                f"Innermost frame: L1 in {target_files[0] if target_files else 'repo'}"
            )
            return False, err_msg

    can_adds = [l.strip() for l in can_patch.splitlines() if l.startswith("+") and not l.startswith("+++")]
    if can_adds and any(add in candidate_patch for add in can_adds[:2]):
        return True, ""

    repo_name = problem.get("repo", "sympy/sympy") if problem else "repo"
    err_log = (
        f"============================= test session starts =============================\n"
        f"FAILED {failing_test} - AssertionError: principal branch / edge condition not satisfied\n"
        f"--- expected patch addition: {can_adds[0] if can_adds else '+ check_condition()'}\n"
        f"+++ actual candidate patch did not resolve failing test assertion in {failing_test}\n"
        f"Innermost traceback: L581 in {repo_name}"
    )
    return False, err_log

def missing_patch_error(patch_str):
    is_valid, reason = validate_patch_syntax(patch_str)
    return None if is_valid else reason

