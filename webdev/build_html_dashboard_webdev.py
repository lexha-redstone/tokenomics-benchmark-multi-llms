def load_results():
    results_dir = os.path.join(HERE, "results")
    files = glob.glob(os.path.join(results_dir, "results_webdev_real_*.json"))
    if not files:
        # Fall back to results_webdev_real.json
        fallback = os.path.join(results_dir, "results_webdev_real.json")
        if os.path.exists(fallback):
            files = [fallback]
        else:
            print("Error: No JSON results found!")
            return []
    latest_file = sorted(files)[-1]
    print(f"Loading results from: {latest_file}")
    with open(latest_file) as f:
        return json.load(f)

